// HR documents strictly EXCLUDED
export const HR_SERVICE_EXCLUSIONS = [
  "employeeAppraisal",
  "healthyLivingLog",
  "staffFileNote",
  "sicknessReview",
  "firstWrittenWarning",
  "teamMeeting",
];

// Helper to determine if a service is eligible for medication recommendations
export function isConsultationService(serviceId) {
  if (!serviceId) return false;
  return !HR_SERVICE_EXCLUSIONS.includes(serviceId);
}

// Helper to get grouped recommendations for a specific service and optional condition filter
export function getRecommendationsForService(serviceId, selectedCondition = "all") {
  if (!isConsultationService(serviceId)) return {};

  let items = [];

  if (serviceId === "weightloss" || serviceId === "weightlossFollowup") {
    // 1. Weightloss & Weightloss Follow Up: all weightloss medicines
    items = WEIGHT_LOSS_RECOMMENDATIONS;
  } else if (serviceId === "travel" || serviceId === "travelFollowUp") {
    // 2. Travel Clinic & Travel Follow Up: all travel vaccination service medicines
    items = TRAVEL_RECOMMENDATIONS;
  } else {
    // 3. All remaining private & Pharmacy First services: feature all Pharmacy First & private medicines
    items = PHARMACY_FIRST_AND_PRIVATE_RECOMMENDATIONS;

    // Optional condition filtering for Pharmacy First & Private services
    if (selectedCondition && selectedCondition !== "all") {
      items = items.filter((item) => {
        if (selectedCondition === "wellbeing") {
          return item.category === "General wellbeing" || item.condition === "wellbeing";
        }
        return item.condition === selectedCondition;
      });
    }
  }

  // Group items by category maintaining natural order
  const grouped = {};
  items.forEach((item) => {
    if (!grouped[item.category]) {
      grouped[item.category] = [];
    }
    grouped[item.category].push(item);
  });

  return grouped;
}
